from src.editorial_quality_policy import editorial_value_ok


def test_rejects_generic_why_it_matters():
    assert not editorial_value_ok(
        "آزمایش جدید یک مدل AI",
        "پژوهشگران یک مدل AI را آموزش دادند و دقت آن را در یک ارزیابی افزایش دادند. نتیجه نشان می‌دهد روش جدید در همان مجموعه‌داده عملکرد بهتری دارد.",
        "این پیشرفت می‌تواند آینده هوش مصنوعی را تغییر دهد و اهمیت زیادی دارد.",
        "پژوهشگران یک مدل AI را آموزش دادند و دقت آن را در یک ارزیابی افزایش دادند. نتیجه نشان می‌دهد روش جدید در همان مجموعه‌داده عملکرد بهتری دارد.",
    )


def test_rejects_summary_without_concrete_information():
    assert not editorial_value_ok(
        "خبر تازه درباره هوش مصنوعی",
        "این پژوهش درباره یک موضوع مهم در هوش مصنوعی است و نکات تازه‌ای را مطرح می‌کند.",
        "این موضوع برای آینده فناوری مهم است و می‌تواند کاربردهای مختلفی داشته باشد.",
        "این پژوهش درباره یک موضوع مهم در هوش مصنوعی است و نکات تازه‌ای را مطرح می‌کند. جزئیات فنی بیشتری در منبع آمده است.",
    )


def test_rejects_summary_why_duplication():
    text = "پژوهشگران یک مدل LLM جدید ساختند که در ارزیابی کدنویسی عملکرد بهتری دارد و هزینه استنتاج را کاهش می‌دهد."
    assert not editorial_value_ok(
        "مدل جدید LLM برای کدنویسی",
        text,
        text,
        text + " جزئیات آزمایش در مقاله منتشر شده است.",
    )


def test_accepts_specific_summary_and_concrete_impact():
    summary = "پژوهشگران یک روش جدید برای آموزش LLM ارائه کردند که در ارزیابی کدنویسی دقت را 12 درصد افزایش داد. آزمایش‌ها روی سه مجموعه‌داده انجام شد و نویسندگان کاهش هزینه استنتاج را نیز گزارش کردند."
    why = "اگر این نتیجه در داده‌های مستقل تکرار شود، می‌تواند هزینه استقرار عامل‌های کدنویسی را کاهش دهد و فاصله میان کیفیت مدل و هزینه اجرا را کمتر کند. در عین حال، محدود بودن آزمایش به سه مجموعه‌داده باعث می‌شود تعمیم‌پذیری هنوز نیازمند بررسی باشد."
    assert editorial_value_ok("روش جدید آموزش LLM", summary, why, summary + " " + why)
